// splice
var arr = [1, 2, 3, 4, 5];
console.log(arr);

// adicionar um elemento ao array
arr.splice(2, 0, 999);
console.log(arr);

// remover um elemento do array
arr.splice(4, 1);
console.log(arr);

// indexOf = encontrar o índice do elemento
console.log(arr.indexOf(5));

// join
var arr2 = ["O", "rato", "roeu", "a", "roupa"];
console.log(arr2.join(" "));

// reverse
console.log(arr2.reverse());